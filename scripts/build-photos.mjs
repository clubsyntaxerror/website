// Turns photos in public/ into C64 multicolour-style pictures for the adventure theme:
// 160 pixels across (each twice as wide as tall), the sixteen C64 colours, Floyd-Steinberg dithered.
// Run `npm run photos` after adding or changing a photo below; the output is committed,
// so nothing image-related runs at build time or on the server.
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";

const PHOTOS = {
    crew: { file: "public/photos/crew.jpg", alt: "The Syntax Error crew, in costume" },
    artists: { file: "public/photos/artists.jpg", alt: "An artist playing live at Syntax Error" },
    dancefloor: { file: "public/video-poster.jpg", alt: "The Syntax Error dance floor" },
};

const OUT_DIR = "public/adventure";
const META = "src/themes/adventure/photos.generated.ts";
const WIDTH = 160;
const MAX_HEIGHT = 200; // the C64 screen is 160x200 in multicolour mode

const PALETTE = [
    "#000000",
    "#ffffff",
    "#813338",
    "#75cec8",
    "#8e3c97",
    "#56ac4d",
    "#2e2c9b",
    "#edf171",
    "#8e5029",
    "#553800",
    "#c46c71",
    "#4a4a4a",
    "#7b7b7b",
    "#a9ff9f",
    "#706deb",
    "#b2b2b2",
].map((hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16)));

// Error diffusion strength: below 1 keeps flat areas calmer.
const DAMPING = 0.8;

const dist = (a, b) => (a[0] - b[0]) ** 2 * 0.3 + (a[1] - b[1]) ** 2 * 0.59 + (a[2] - b[2]) ** 2 * 0.11;

async function convert(name, { file }) {
    const meta = await sharp(file).metadata();
    // Pixels are 2:1, so a picture shown 320 units wide needs one row per unit of height.
    const height = Math.min(MAX_HEIGHT, Math.round((WIDTH * 2 * meta.height) / meta.width));
    const { data } = await sharp(file)
        .resize(WIDTH, height, { fit: "cover", kernel: "lanczos3" })
        .modulate({ saturation: 1.25 })
        .removeAlpha()
        .raw()
        .toBuffer({ resolveWithObject: true });

    const work = Float32Array.from(data);
    const out = Buffer.alloc(WIDTH * height * 3);
    for (let y = 0; y < height; y++)
        for (let x = 0; x < WIDTH; x++) {
            const i = (y * WIDTH + x) * 3;
            const px = [work[i], work[i + 1], work[i + 2]];
            let best = PALETTE[0];
            let bestDist = Infinity;
            for (const color of PALETTE) {
                const d = dist(px, color);
                if (d < bestDist) [best, bestDist] = [color, d];
            }
            for (let k = 0; k < 3; k++) {
                out[i + k] = best[k];
                const err = (px[k] - best[k]) * DAMPING;
                if (x + 1 < WIDTH) work[i + 3 + k] += (err * 7) / 16;
                if (y + 1 < height) {
                    const below = i + WIDTH * 3 + k;
                    if (x > 0) work[below - 3] += (err * 3) / 16;
                    work[below] += (err * 5) / 16;
                    if (x + 1 < WIDTH) work[below + 3] += err / 16;
                }
            }
        }

    await sharp(out, { raw: { width: WIDTH, height, channels: 3 } })
        .png({ palette: true, colours: 16, dither: 0 })
        .toFile(`${OUT_DIR}/${name}.png`);
    return { width: WIDTH * 2, height };
}

await mkdir(OUT_DIR, { recursive: true });
const entries = [];
for (const [name, photo] of Object.entries(PHOTOS)) {
    const { width, height } = await convert(name, photo);
    entries.push(
        `    ${name}: { src: "/adventure/${name}.png", width: ${width}, height: ${height}, alt: ${JSON.stringify(photo.alt)} },`,
    );
    console.log(`${name}: ${width / 2}x${height}`);
}

await writeFile(
    META,
    `// Generated by scripts/build-photos.mjs. Do not edit; run \`npm run photos\`.\n` +
        `export const PHOTOS = {\n${entries.join("\n")}\n} as const;\n\nexport type PhotoName = keyof typeof PHOTOS;\n`,
);
