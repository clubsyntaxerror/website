// Turns photos in public/ into teletext mosaic graphics for the teletext theme.
// Run `npm run mosaics` after adding or changing a photo below; the output is committed,
// so nothing image-related runs at build time or on the server.
import sharp from "sharp";
import { writeFile } from "node:fs/promises";

const PHOTOS = {
    crew: { file: "public/photos/crew.jpg", alt: "Syntax Error crew" },
    artists: { file: "public/photos/artists.jpg", alt: "Artist playing at Syntax Error" },
    dancefloor: { file: "public/video-poster.jpg", alt: "The Syntax Error dance floor" },
};

const OUT = "src/themes/teletext/photos.generated.ts";
const WIDTH = 80; // sixels: 40 cells x 2
const MAX_ROWS = 10; // cell rows
// A sixel is 0.2em wide and 1.15em / 3 tall on the teletext grid.
const SIXEL_ASPECT = 1.15 / 3 / 0.2;

// Teletext colours, index = colour code (0 = black background).
const PALETTE = [
    [0, 0, 0],
    [255, 0, 0],
    [0, 255, 0],
    [255, 255, 0],
    [0, 0, 255],
    [255, 0, 255],
    [0, 255, 255],
    [255, 255, 255],
];

// How far from grey (0-255) a cell's average colour must be to get a colour instead of white.
const SATURATION = 60;
const CONTRAST = 9;
const DAMPING = 0.7;

const dist = (a, b) => (a[0] - b[0]) ** 2 * 0.3 + (a[1] - b[1]) ** 2 * 0.59 + (a[2] - b[2]) ** 2 * 0.11;

async function convert({ file }) {
    const meta = await sharp(file).metadata();
    const cellRows = Math.min(MAX_ROWS, Math.round((WIDTH * (meta.height / meta.width)) / SIXEL_ASPECT / 3));
    const height = cellRows * 3;
    const { data } = await sharp(file)
        .resize(WIDTH, height, { fit: "cover", kernel: "lanczos3" })
        .modulate({ saturation: 1.4 })
        .normalise()
        .removeAlpha()
        .raw()
        .toBuffer({ resolveWithObject: true });

    const px = (x, y) => {
        const i = (y * WIDTH + x) * 3;
        return [data[i], data[i + 1], data[i + 2]];
    };

    // Shape comes from luminance, dithered with Floyd-Steinberg at sixel level.
    const lum = new Float32Array(WIDTH * height);
    for (let y = 0; y < height; y++)
        for (let x = 0; x < WIDTH; x++) {
            const [r, g, b] = px(x, y);
            // S-curve: push dim backgrounds to black and highlights to full, so shapes survive 80 px.
            const l = (r * 0.3 + g * 0.59 + b * 0.11) / 255;
            lum[y * WIDTH + x] = 1 / (1 + Math.exp(-CONTRAST * (l - 0.5)));
        }
    const lit = new Uint8Array(WIDTH * height);
    for (let y = 0; y < height; y++)
        for (let x = 0; x < WIDTH; x++) {
            const i = y * WIDTH + x;
            const on = lum[i] > 0.5;
            lit[i] = on ? 1 : 0;
            // Damped error spreads less noise into flat areas.
            const err = (lum[i] - (on ? 1 : 0)) * DAMPING;
            if (x + 1 < WIDTH) lum[i + 1] += (err * 7) / 16;
            if (y + 1 < height) {
                if (x > 0) lum[i + WIDTH - 1] += (err * 3) / 16;
                lum[i + WIDTH] += (err * 5) / 16;
                if (x + 1 < WIDTH) lum[i + WIDTH + 1] += err / 16;
            }
        }

    // Real teletext allows one foreground colour per cell: the palette hue nearest the cell's average,
    // or white when the cell is close to grey.
    const out = new Uint8Array(WIDTH * height);
    for (let cy = 0; cy < cellRows; cy++)
        for (let cx = 0; cx < WIDTH / 2; cx++) {
            const sum = [0, 0, 0];
            for (let sy = 0; sy < 3; sy++)
                for (let sx = 0; sx < 2; sx++) px(cx * 2 + sx, cy * 3 + sy).forEach((v, k) => (sum[k] += v / 6));
            const max = Math.max(...sum);
            const min = Math.min(...sum);
            let color = 7;
            if (max - min > SATURATION) {
                // Normalise to full brightness, then pick the closest saturated colour.
                const hue = sum.map((v) => ((v - min) / (max - min)) * 255);
                let best = Infinity;
                for (let c = 1; c < 7; c++) {
                    const d = dist(hue, PALETTE[c]);
                    if (d < best) [best, color] = [d, c];
                }
            }
            for (let sy = 0; sy < 3; sy++)
                for (let sx = 0; sx < 2; sx++) {
                    const i = (cy * 3 + sy) * WIDTH + cx * 2 + sx;
                    out[i] = lit[i] ? color : 0;
                }
        }
    return { rows: cellRows, data: Buffer.from(out.map((v) => 48 + v)).toString("latin1") };
}

const entries = [];
for (const [name, photo] of Object.entries(PHOTOS)) {
    const { rows, data } = await convert(photo);
    entries.push(`    ${name}: { rows: ${rows}, alt: ${JSON.stringify(photo.alt)}, data: ${JSON.stringify(data)} },`);
    console.log(`${name}: ${rows} rows`);
}

await writeFile(
    OUT,
    `// Generated by scripts/build-mosaics.mjs from photos in public/. Do not edit; run \`npm run mosaics\`.\n` +
        `// prettier-ignore\n` +
        `export const PHOTOS = {\n${entries.join("\n")}\n} as const;\n\nexport type PhotoName = keyof typeof PHOTOS;\n`,
);
